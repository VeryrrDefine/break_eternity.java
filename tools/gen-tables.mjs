#!/usr/bin/env node
/**
 * Generates src/main/java/breaketernity/CriticalTables.java from the original
 * break_eternity.js src/index.ts.
 *
 * The critical-section tables are 10x11 grids of doubles that drive analytic
 * tetration/slog for bases <= 10. Transcribing them by hand risks silent digit
 * errors, so they are lifted verbatim from the original source and printed with
 * the shortest round-trip representation (Number.prototype.toString), which is
 * exact for doubles.
 *
 * Usage: node tools/gen-tables.mjs [path/to/break_eternity.js]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const originalRepo = resolve(process.argv[2] ?? resolve(here, "..", "..", "break_eternity.js"));
const sourcePath = resolve(originalRepo, "src", "index.ts");
const source = readFileSync(sourcePath, "utf8");

/** Extracts the literal initializer of `const <name> = <[ ... ]>;` via bracket matching. */
function extractLiteral(name) {
  const start = source.indexOf(`const ${name} = `);
  if (start === -1) throw new Error(`could not find const ${name}`);
  const open = source.indexOf("[", start);
  let depth = 0;
  for (let i = open; i < source.length; i++) {
    const c = source[i];
    if (c === "[") depth++;
    else if (c === "]") {
      depth--;
      if (depth === 0) return source.slice(open, i + 1);
    }
  }
  throw new Error(`unterminated literal for ${name}`);
}

/** Shortest round-trip representation of a number, in Java-compatible syntax. */
function num(x) {
  if (x === Infinity) return "Double.POSITIVE_INFINITY";
  if (x === -Infinity) return "Double.NEGATIVE_INFINITY";
  if (Number.isNaN(x)) return "Double.NaN";
  const s = String(x);
  // A bare integer literal that does not fit in an int is a compile error in Java
  // even when assigned to a double, so suffix those with "d" ("1e21" is fine as-is).
  if (!/[.eE]/.test(s) && Math.abs(x) > 2147483647) {
    return s + "d";
  }
  return s;
}

function rows(literal) {
  const value = new Function(`return ${literal};`)();
  return value.map((row) => {
    if (Array.isArray(row)) return `        { ${row.map(num).join(", ")} },`;
    return `        ${num(row)},`;
  });
}

const headers = extractLiteral("critical_headers");
const tetr = extractLiteral("critical_tetr_values");
const slog = extractLiteral("critical_slog_values");

const omega = 0.56714329040978387299997;
const layerDown = Math.log10(9e15);
const firstNegLayer = 1 / 9e15;
const maxSafeInteger = Number.MAX_SAFE_INTEGER;
const maxValue = Number.MAX_VALUE;
const minValue = Number.MIN_VALUE;

const out = `package breaketernity;

/**
 * Numeric tables and module-level constants transcribed from the original
 * break_eternity.js src/index.ts (lines 5-183, v2.1.3).
 *
 * <p>GENERATED by tools/gen-tables.mjs from the original source. Do not edit by hand.
 */
public final class CriticalTables {
    private CriticalTables() {}

    /** Maximum number of digits of precision to assume in a double. */
    public static final int MAX_SIGNIFICANT_DIGITS = 17;
    /** If we're ABOVE this value, increase a layer. (Close to the largest integer that fits in a double.) */
    public static final double EXP_LIMIT = ${num(9e15)};
    /** ${"Math.log10(9e15)"} - below this, the layer is decremented once layer > 0. */
    public static final double LAYER_DOWN = ${num(layerDown)};
    /** At layer 0, smaller non-zero numbers than this become layer 1 numbers with negative mag. */
    public static final double FIRST_NEG_LAYER = ${num(firstNegLayer)};
    /** The largest exponent that can appear in a double, though not all mantissas are valid here. */
    public static final int NUMBER_EXP_MAX = 308;
    /** The smallest exponent that can appear in a double, though not all mantissas are valid here. */
    public static final int NUMBER_EXP_MIN = -324;
    /** For default toString behaviour, when to swap from eee... to (e^n) syntax. */
    public static final int MAX_ES_IN_A_ROW = 5;
    /** The default size of the LRU cache used to cache Decimal.fromString. */
    public static final int DEFAULT_FROM_STRING_CACHE_SIZE = ${(1 << 10) - 1};
    /** Comma handling in fromString. */
    public static final boolean IGNORE_COMMAS = true;
    /** Comma handling in fromString. If IGNORE_COMMAS is true, this is not consulted. */
    public static final boolean COMMAS_ARE_DECIMAL_POINTS = false;
    /** W(1, 0), the omega constant. */
    public static final double OMEGA = ${num(omega)};

    /** Number.MAX_SAFE_INTEGER, used by dLayerSafeMax/dLaySafeMin. */
    public static final double MAX_SAFE_INTEGER = ${num(maxSafeInteger)};
    /** Number.MAX_VALUE. */
    public static final double MAX_VALUE = ${num(maxValue)};
    /** Number.MIN_VALUE (the smallest positive subnormal, 5e-324). */
    public static final double MIN_VALUE = ${num(minValue)};

    /**
     * The bases for which critical values are tabulated: 2, e, 3, 4, ..., 10.
     * See Patashu/break_eternity.js issue #22 and the comments above the tables
     * in the original source for how these were derived.
     */
    public static final double[] critical_headers = {
${rows(headers).join("\n")}
    };

    /**
     * critical_tetr_values[baseIndex][k] = critical_headers[baseIndex]^^(k/10),
     * i.e. the column k holds base^^(k/10) for k = 0..10.
     */
    public static final double[][] critical_tetr_values = {
${rows(tetr).join("\n")}
    };

    /**
     * critical_slog_values[baseIndex][k] = slog_critical_headers[baseIndex](k/10),
     * i.e. the super-logarithm of k/10 for k = 0..10.
     */
    public static final double[][] critical_slog_values = {
${rows(slog).join("\n")}
    };
}
`;

const outPath = resolve(here, "..", "src", "main", "java", "breaketernity", "CriticalTables.java");
writeFileSync(outPath, out);
const evalLiteral = (literal) => new Function(`return ${literal};`)();

console.log(`Wrote ${outPath} from ${sourcePath}`);
console.log(
  `Headers: ${evalLiteral(headers).length}, ` +
    `tetr rows: ${evalLiteral(tetr).length}, ` +
    `slog rows: ${evalLiteral(slog).length}`,
);
